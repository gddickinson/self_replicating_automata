"""Generate tests/fixtures/engine_fixtures.json: Python reference grids for the browser engine.

* "inits": each class's constructor grid at every lab size (the GUIs' 50..300 slider values), stored sparsely;
  Brian's Brain after np.random.seed(seed) for a few seeds.
* "runs": start grids and the grids the real Python step() reaches after N steps: every constructor default,
  a seeded random soup over all of the automaton's states, a Langton soup dense in the states its rules use,
  and the small patterns from test_automata.py.
* "rules" / "gun": the Langton rule table and the Gosper gun as read from the Python objects.

The node test web/static/automata_engine.test.mjs asserts the JS engine reproduces every case cell for cell, and
tests/test_web.py checks the fixtures are still current (inits directly, runs through POST /api/run).

Run: python scripts/make_engine_fixtures.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from web import catalogue as cat  # noqa: E402
from web.grid_codec import encode  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "engine_fixtures.json"
BRAIN_SEEDS, BRAIN_SIZES = (0, 1, 42), (50, 100)
RUN_SIZE = 50
RUN_STEPS = {"langton_loop": 10, "brians_brain": 40, "game_of_life": 120, "wireworld": 60}
SOUP, SOUP_STEPS = 24, 12


def sparse(grid) -> list:
    """Nonzero cells as [flat_index, value] pairs (row-major)."""
    flat = np.asarray(grid).ravel()
    idx = np.flatnonzero(flat)
    return [[int(i), int(flat[i])] for i in idx]


def init_cases() -> list:
    out = []
    for key in cat.AUTOMATA:
        if key == "brians_brain":
            combos = [(n, s) for n in BRAIN_SIZES for s in BRAIN_SEEDS]
        else:
            combos = [(n, None) for n in cat.SIZES]
        for n, seed in combos:
            a = cat.make(key, n, n, seed if seed is not None else 0)
            out.append({"key": key, "size": n, "seed": seed, "nonzero": sparse(a.grid)})
    return out


def run_case(key, label, grid, steps):
    h, w = grid.shape
    res = cat.run(key, encode(grid), w, h, steps)
    return {"key": key, "label": label, "width": w, "height": h, "steps": steps,
            "start": encode(grid), "end": res["cells"], "generation": res["generation"]}


def soup(states, w, h, seed, p=None):
    return np.random.default_rng(seed).choice(states, size=(h, w), p=p).astype(np.int32)


def test_patterns():
    """The hand-made grids of test_automata.py (on a 10 x 10 grid, as there)."""
    out = []
    g = np.zeros((10, 10), np.int32); g[5, 4:7] = 1
    out.append(("game_of_life", "test_blinker_oscillates", g, 3))
    g = np.zeros((10, 10), np.int32); g[5, 5] = 1; g[5, 6] = 2
    out.append(("wireworld", "test_wire_with_one_head_becomes_head", g, 3))
    g = np.zeros((10, 10), np.int32); g[4, 5] = 1; g[6, 5] = 1
    out.append(("brians_brain", "test_birth_with_two_neighbors", g, 6))
    return out


def run_cases() -> list:
    cases = []
    for i, entry in enumerate(cat.catalogue()):
        key = entry["key"]
        a = cat.make(key, RUN_SIZE, RUN_SIZE, 0)
        cases.append(run_case(key, f"constructor default {RUN_SIZE}x{RUN_SIZE}", a.grid.copy(), RUN_STEPS[key]))
        cases.append(run_case(key, "random soup, all states", soup(entry["num_states"], SOUP, SOUP, 100 + i),
                              SOUP_STEPS))
    p = [0.55, 0.3, 0.15]
    for seed in (1, 2):
        cases.append(run_case("langton_loop", f"soup of states 0-2 (seed {seed})", soup(3, SOUP, SOUP, seed, p), 8))
    for key, label, g, steps in test_patterns():
        cases.append(run_case(key, label, g, steps))
    return cases


def build() -> dict:
    return {"note": "generated by scripts/make_engine_fixtures.py; do not edit",
            "rules": cat.langton_rules(), "gun": cat.gosper_gun(), "sizes": cat.SIZES,
            "inits": init_cases(), "runs": run_cases()}


if __name__ == "__main__":
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, separators=(",", ":")))
    print(f"{len(data['inits'])} init grids, {len(data['runs'])} run cases -> {OUT} ({OUT.stat().st_size / 1e3:.0f} kB)")
